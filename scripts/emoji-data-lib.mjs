const GROUPS = new Set([
  "Smileys & Emotion",
  "People & Body",
  "Animals & Nature",
  "Food & Drink",
  "Activities",
  "Travel & Places",
  "Objects",
  "Symbols",
  "Flags",
]);

function decodeXml(value) {
  return value
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(Number.parseInt(hex, 16)))
    .replace(/&#([0-9]+);/g, (_, decimal) => String.fromCodePoint(Number.parseInt(decimal, 10)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

export function parseEmojiTest(source) {
  const records = [];
  let group = "";

  for (const rawLine of source.split(/\r?\n/)) {
    const groupMatch = rawLine.match(/^# group: (.+)$/);
    if (groupMatch) {
      group = groupMatch[1].trim();
      continue;
    }
    if (!GROUPS.has(group)) continue;

    const match = rawLine.match(/^([0-9A-F ]+)\s*;\s*fully-qualified\s*#\s*(\S+)/);
    if (!match) continue;
    const codePoints = match[1].trim().split(/\s+/);
    records.push({
      id: codePoints.join("-"),
      emoji: String.fromCodePoint(...codePoints.map((value) => Number.parseInt(value, 16))),
      group,
      order: records.length,
    });
  }

  return records;
}

export function parseAnnotationsXml(source) {
  const annotations = new Map();
  const pattern = /<annotation\b([^>]*)>([\s\S]*?)<\/annotation>/g;
  for (const match of source.matchAll(pattern)) {
    const attributes = match[1];
    const cpMatch = attributes.match(/\bcp="([^"]+)"/);
    if (!cpMatch) continue;
    const emoji = decodeXml(cpMatch[1]);
    const value = decodeXml(match[2].replace(/<[^>]+>/g, "").trim());
    const current = annotations.get(emoji) ?? { name: "", keywords: [] };
    if (/\btype="tts"/.test(attributes)) {
      current.name = value;
    } else {
      current.keywords = value.split("|").map((item) => item.trim()).filter(Boolean);
    }
    annotations.set(emoji, current);
  }
  return annotations;
}

function mergeAnnotationSources(sources) {
  const result = new Map();
  for (const source of sources) {
    for (const [emoji, annotation] of parseAnnotationsXml(source)) {
      const current = result.get(emoji) ?? { name: "", keywords: [] };
      result.set(emoji, {
        name: annotation.name || current.name,
        keywords: annotation.keywords.length > 0 ? annotation.keywords : current.keywords,
      });
    }
  }
  return result;
}

export function buildEmojiRecords(emojiTest, englishSources, traditionalChineseSources) {
  const english = mergeAnnotationSources(englishSources);
  const traditionalChinese = mergeAnnotationSources(traditionalChineseSources);

  return parseEmojiTest(emojiTest).map((record) => {
    const englishAnnotation = english.get(record.emoji) ?? { name: "", keywords: [] };
    const chineseAnnotation = traditionalChinese.get(record.emoji) ?? { name: "", keywords: [] };
    const fallbackName = englishAnnotation.name || record.emoji;
    return {
      ...record,
      nameEn: fallbackName,
      nameZhHant: chineseAnnotation.name || fallbackName,
      keywordsEn: englishAnnotation.keywords,
      keywordsZhHant: chineseAnnotation.keywords,
    };
  });
}

export function renderEmojiModule(records) {
  return `// Generated by scripts/generate-emoji-data.mjs. Do not edit by hand.\n` +
    `// Sources: Unicode Emoji 17.0 / Unicode 17.0.0 and CLDR release-48.\n` +
    `// Terms: https://www.unicode.org/terms_of_use.html\n\n` +
    `export type EmojiGroup =\n` +
    `  | "Smileys & Emotion"\n  | "People & Body"\n  | "Animals & Nature"\n` +
    `  | "Food & Drink"\n  | "Activities"\n  | "Travel & Places"\n` +
    `  | "Objects"\n  | "Symbols"\n  | "Flags";\n\n` +
    `export interface EmojiRecord {\n  id: string;\n  emoji: string;\n  group: EmojiGroup;\n` +
    `  order: number;\n  nameEn: string;\n  nameZhHant: string;\n` +
    `  keywordsEn: string[];\n  keywordsZhHant: string[];\n}\n\n` +
    `export const EMOJI_DATA_VERSION = { emoji: "17.0", unicode: "17.0.0", cldr: "48" } as const;\n\n` +
    `export const EMOJI_DATA: readonly EmojiRecord[] = ${JSON.stringify(records, null, 2)};\n`;
}
