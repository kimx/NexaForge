// Optional browser acceptance checks; requires Playwright locally.
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium } from 'playwright';

const base = process.env.AUDIT_BASE_URL || 'http://127.0.0.1:4187';
const out = resolve(process.env.AUDIT_OUTPUT || 'artifacts/personal-workflows');
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const results = [];
const source = '  pear  \n\n apple \n PEAR ';
try {
  for (const locale of ['en', 'zh']) for (const mobile of [false, true]) {
    const english = locale === 'en';
    const name = `${locale}-${mobile ? 'mobile' : 'desktop'}`;
    const prefix = english ? '/en' : '';
    const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, isMobile: mobile, hasTouch: mobile, acceptDownloads: true });
    const page = await context.newPage();
    await context.grantPermissions(['clipboard-read', 'clipboard-write']);
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const goto = async path => { await page.goto(`${base}${prefix}${path}`, { waitUntil: 'networkidle' }); };
    await goto('/text/list-cleanup');
    const input = page.locator('#list-cleanup-input');
    const output = page.locator('#list-cleanup-output');
    await input.fill(source);
    assert.ok(await output.count() === 0 || await output.inputValue() === '');
    await page.getByRole('button', { name: english ? 'Run cleanup' : '執行清理', exact: true }).click();
    assert.equal(await output.inputValue(), 'apple\npear');
    assert.equal(await input.inputValue(), source);
    assert.equal(await page.locator('.list-cleanup__preview').count(), 3);
    await page.getByRole('button', { name: english ? 'Copy result' : '複製結果', exact: true }).click();
    assert.equal((await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, '\n'), 'apple\npear');
    const templateName = page.getByLabel(english ? 'Template name' : '範本名稱', { exact: true });
    await templateName.fill('Weekly list');
    await page.getByRole('button', { name: english ? 'Save new template' : '儲存新範本', exact: true }).click();
    await templateName.fill('Weekly roster');
    await page.getByRole('button', { name: english ? 'Rename template' : '重新命名範本', exact: true }).click();
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: english ? 'Download .txt' : '下載文字檔', exact: true }).click();
    await (await download).saveAs(resolve(out, `${name}.txt`));
    assert.equal(await readFile(resolve(out, `${name}.txt`), 'utf8'), 'apple\npear');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.ok(await page.locator('.list-cleanup .tool-actions .btn').evaluateAll(buttons => buttons.every(button => {
      const box = button.getBoundingClientRect();
      const parent = button.parentElement.getBoundingClientRect();
      return box.left >= parent.left - 1 && box.right <= parent.right + 1 && box.height < 120;
    })), 'Action buttons must fit their panel without clipping or stretching');
    if (!mobile) assert.ok(await page.locator('.tool-page__panel--options').evaluate(el => el.getBoundingClientRect().width) >= 288);
    await page.screenshot({ path: resolve(out, `${name}-list.png`), fullPage: true });
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await input.inputValue(), '');
    await page.locator('#list-cleanup-templates').selectOption('Weekly roster');
    await input.fill(source);
    assert.ok(await output.count() === 0 || await output.inputValue() === '');
    await page.getByRole('button', { name: english ? 'Run cleanup' : '執行清理', exact: true }).click();
    assert.equal(await output.inputValue(), 'apple\npear');
    await page.getByRole('button', { name: english ? 'Pin List Cleanup' : '釘選 清單清理', exact: true }).click();

    await goto('/image/compress');
    await page.getByLabel(english ? 'Output Format' : '輸出格式').selectOption('webp');
    const quality = page.getByRole('slider');
    await quality.focus();
    for (let i = 0; i < 17; i++) await quality.press('ArrowLeft');
    const savedQuality = await quality.inputValue();
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.getByLabel(english ? 'Output Format' : '輸出格式').inputValue(), 'webp');
    assert.equal(await quality.inputValue(), savedQuality);
    await goto('/text/text-cleaner');
    await page.getByLabel(english ? 'Input text' : '輸入文字', { exact: true }).fill('private original customer');
    await page.getByLabel(english ? 'Trim each line' : '移除每行前後空白', { exact: true }).check();
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.getByLabel(english ? 'Input text' : '輸入文字', { exact: true }).inputValue(), '');
    assert.equal(await page.getByLabel(english ? 'Trim each line' : '移除每行前後空白', { exact: true }).isChecked(), true);
    await goto('/text/hash');
    await goto('/text/uuid');
    await goto('/');
    const recent = await page.evaluate(() => JSON.parse(localStorage.getItem('nexaforge-recent-tools')));
    assert.deepEqual(recent, ['uuid', 'hash', 'text-cleaner', 'image-compress']);
    assert.equal(await page.getByTestId('pinned-tools').getByRole('article').count(), 1);
    assert.equal(await page.getByTestId('recent-tools').getByRole('article').count(), 4);
    await page.screenshot({ path: resolve(out, `${name}-home.png`), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const storage = await page.evaluate(() => JSON.stringify(Object.entries(localStorage)));
    assert.ok(!storage.includes('private original customer') && !storage.includes('pear') && !storage.includes('apple'));
    await page.getByText(english ? 'Personal settings' : '個人設定', { exact: true }).click();
    await page.locator('.personal-settings').getByRole('button', { name: english ? 'Clear recent tools' : '清除最近使用工具', exact: true }).click();
    assert.equal(await page.getByTestId('recent-tools').count(), 0);
    assert.equal(await page.getByTestId('pinned-tools').count(), 1);
    await page.locator('.personal-settings').getByRole('button', { name: english ? 'Clear pinned tools' : '清除釘選工具', exact: true }).click();
    assert.equal(await page.getByTestId('pinned-tools').count(), 0);
    assert.ok(await page.evaluate(() => localStorage.getItem('nexaforge-list-templates-v1')?.includes('Weekly roster')));
    assert.ok(errors.every(message => message.startsWith('Minified React error #421;')), 'No unexpected runtime errors');
    results.push({ name, recent, savedQuality, errors });
    console.log(`PASS ${name}`);
    await context.close();
  }
  await writeFile(resolve(out, 'results.json'), JSON.stringify({ base, checkedAt: new Date().toISOString(), results }, null, 2));
} finally { await browser.close(); }
